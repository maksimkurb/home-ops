#!/usr/bin/env bash
# Regenerates the cleaned CA bundle used by trust-manager.
#
# Downloads the current Mozilla bundle (https://curl.se/ca/cacert.pem) and removes
# distrusted roots (eMudhra / emSign compromise, Oct 2026) by SHA-256 fingerprint
# and by subject (emSign|eMudhra).
#
# AAA Certificate Services (Sectigo legacy root) is ALSO removed, because the
# compromised eMudhra intermediates have cross-signed copies chaining to it.
# This can break sites still chained only to AAA (old Comodo/Sectigo chains).
# To keep it:  KEEP_AAA=1 hack/update-trusted-ca-bundle.sh
#
# Usage: hack/update-trusted-ca-bundle.sh [path-to-local-cacert.pem]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/cluster/apps/kube-system/trust-manager/bundle/ca-certificates.crt"
SRC_URL="https://curl.se/ca/cacert.pem"
KEEP_AAA="${KEEP_AAA:-0}"

# SHA-256 fingerprints (uppercase hex, no colons) to remove.
BLOCK=(
  86A1ECBA089C4A8D3BBE2734C612BA341D813E043CF9E8A862CD5C57A36BBE6B # emSign ECC Root CA - G3
  7DD78D5F4F13459A83DFF9ABBBA62EDBAF6F2D102BF257FD712F4D9F2746ED8D # emSign Root TLS CA - G3
  F2EDAAFF3D9B701FB4D14C9F285F8C0BAD90FC3BCC1FA07D47F4718EDABA34A5 # emSign Root CS CA - G3
)
AAA_FP=D7A7A0FB5D7E2731D771E9484EBCDEF71D5F0C3E0A2948782BC83EE0EA699EF4 # AAA Certificate Services
[ "$KEEP_AAA" = "1" ] || BLOCK+=("$AAA_FP")

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

if [ $# -ge 1 ]; then cp "$1" "$WORK/in.pem"; else curl -sSfL -o "$WORK/in.pem" "$SRC_URL"; fi

# Split into individual certs.
awk -v d="$WORK" '/-----BEGIN CERTIFICATE-----/{n++; f=sprintf("%s/c%04d.pem",d,n)} f{print > f} /-----END CERTIFICATE-----/{close(f); f=""}' "$WORK/in.pem"

total=0; kept=0
: > "$WORK/out.pem"
for c in "$WORK"/c*.pem; do
  total=$((total+1))
  fp="$(openssl x509 -in "$c" -noout -fingerprint -sha256 | cut -d= -f2 | tr -d : | tr a-f A-F)"
  subj="$(openssl x509 -in "$c" -noout -subject -nameopt RFC2253)"
  drop=0
  for b in "${BLOCK[@]}"; do [ "$fp" = "$b" ] && drop=1; done
  shopt -s nocasematch
  [[ "$subj" == *emSign* || "$subj" == *eMudhra* ]] && drop=1
  shopt -u nocasematch
  if [ "$drop" = 1 ]; then echo "removed: $subj ($fp)" >&2; continue; fi
  kept=$((kept+1))
  cat "$c" >> "$WORK/out.pem"
done

{
  echo "# Cleaned Mozilla CA bundle (generated by hack/update-trusted-ca-bundle.sh; do not edit)."
  echo "# Source: $SRC_URL  ($(grep -m1 'Certificate data from Mozilla' "$WORK/in.pem" | sed 's/^## //'))"
  echo "# Removed: emSign/eMudhra roots$([ "$KEEP_AAA" = 1 ] || echo ', AAA Certificate Services')"
  cat "$WORK/out.pem"
} > "$OUT"

echo "certs before: $total, after: $kept -> $OUT" >&2
