#!/usr/bin/env python3
"""Regenerate Authelia's OIDC client secret bundle from the SOPS files.

Scans every `cluster/**/*.sops.yaml` Secret for keys named
`*_OAUTH_CLIENT_SECRET` and writes them, one key per client, to
cluster/apps/security/authelia/oidc-clients.sops.yaml (encrypted with sops).

Authelia mounts that Secret at /secrets/oidc, so a client reads its secret with
`client_secret: '{{ secret "/secrets/oidc/<KEY>" }}'`, where <KEY> is the full key
name (e.g. /secrets/oidc/SECRET_HASS_OAUTH_CLIENT_SECRET).

Run locally from anywhere in the repo (needs sops with the age key):
    scripts/sync-authelia-oidc-secrets.py          # write if changed
    scripts/sync-authelia-oidc-secrets.py --check  # exit 1 if out of date
The output is rewritten only when the set of secrets changed, so re-running
does not produce noisy ciphertext diffs.
"""
import argparse
import base64
import pathlib
import re
import subprocess
import sys

import yaml

ROOT = pathlib.Path(subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip())
OUT = ROOT / "cluster/apps/security/authelia/oidc-clients.sops.yaml"
CONFIG = ROOT / "cluster/apps/security/authelia/config/configuration.yml"
KEY_RE = re.compile(r"^[A-Z0-9_]+_OAUTH_CLIENT_SECRET$")
REF_RE = re.compile(r'\{\{\s*secret\s+"/secrets/oidc/([A-Za-z0-9_-]+)"\s*\}\}')

HEADER = """\
---
# GENERATED by scripts/sync-authelia-oidc-secrets.py; do not edit by hand.
# OIDC client secrets for Authelia, one file per client under /secrets/oidc.
# Source of truth: the *_OAUTH_CLIENT_SECRET keys in cluster/**/*.sops.yaml.
"""


def decrypt(path):
    out = subprocess.run(["sops", "-d", str(path)], check=True, capture_output=True, text=True).stdout
    return [d for d in yaml.safe_load_all(out) if isinstance(d, dict)]


def secret_items(doc):
    if doc.get("kind") != "Secret":
        return
    for k, v in (doc.get("stringData") or {}).items():
        yield k, str(v)
    for k, v in (doc.get("data") or {}).items():
        yield k, base64.b64decode(v).decode()


def collect():
    found, origin = {}, {}
    for path in sorted((ROOT / "cluster").rglob("*.sops.yaml")):
        if path == OUT:
            continue
        text = path.read_text()
        if "_OAUTH_CLIENT_SECRET" not in text:
            continue  # key names stay in cleartext under sops; skip decrypting others
        for doc in decrypt(path):
            for key, value in secret_items(doc):
                if not KEY_RE.match(key):
                    continue
                name = key
                if name in found and found[name] != value:
                    sys.exit(f"conflict: {name} differs between {origin[name]} and {path.relative_to(ROOT)}")
                found[name] = value
                origin[name] = path.relative_to(ROOT)
    return found


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only report whether the output is up to date")
    args = ap.parse_args()

    found = collect()
    referenced = set(REF_RE.findall(CONFIG.read_text()))
    missing = sorted(referenced - found.keys())
    if missing:
        sys.exit(f"configuration.yml references secrets with no *_OAUTH_CLIENT_SECRET source: {', '.join(missing)}")
    unused = sorted(found.keys() - referenced)
    if unused:
        print(f"note: not referenced by configuration.yml: {', '.join(unused)}", file=sys.stderr)

    current = {}
    if OUT.exists():
        for doc in decrypt(OUT):
            current.update(dict(secret_items(doc)))
    if current == found:
        print(f"{OUT.relative_to(ROOT)} is up to date ({len(found)} clients)")
        return 0
    if args.check:
        print(f"{OUT.relative_to(ROOT)} is out of date; run {pathlib.Path(__file__).name}")
        return 1

    doc = {"apiVersion": "v1", "kind": "Secret", "metadata": {"name": "authelia-oidc-clients"},
           "type": "Opaque", "stringData": dict(sorted(found.items()))}
    plain = HEADER + yaml.safe_dump(doc, sort_keys=False, default_flow_style=False)
    # Encrypt from stdin so the cleartext never touches the working tree.
    enc = subprocess.run(
        ["sops", "encrypt", "--filename-override", str(OUT.relative_to(ROOT))],
        cwd=ROOT, input=plain, check=True, capture_output=True, text=True,
    ).stdout
    OUT.write_text(enc)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(found)} clients)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
